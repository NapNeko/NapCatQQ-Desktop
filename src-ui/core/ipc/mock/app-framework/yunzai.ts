import type { AppStoreMarketEntry } from '../../types';

/** 形状照后端 yunzai::store::parse_index：id 是 plugins/ 下的目录名，单 JS 是文件名 */
export const yunzaiEntry = (
    id: string,
    name: string,
    description: string,
    author: string,
    home: string,
    tags: string[],
    extra: Partial<AppStoreMarketEntry> = {},
): AppStoreMarketEntry => ({
    resource: 'plugin',
    id,
    name,
    description,
    version: '',
    author,
    homepage: home,
    time: '',
    package: id,
    module_name: id,
    flavor: 'git',
    is_official: tags.includes('推荐'),
    valid: true,
    tags,
    supported_adapters: [],
    authors: [{ name: author, home: '' }],
    repos: [{ url: home, type: 'git', branch: '' }],
    files: [],
    allow_build: [],
    ...extra,
});

